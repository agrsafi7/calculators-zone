// Generates src/data/calculator-manifest.ts — a lightweight, build-time list of
// every calculator (identity + description only, no inputs/formulas/FAQs).
//
// Why: the full calculator configs are ~1.8MB of source. Importing them in the
// main bundle made every page (including the homepage) download all of it,
// hurting mobile load times. The manifest keeps listings, search, counts, and
// the sitemap working from kilobytes; the full configs load on demand per
// category inside GenericCalculatorPage.
import { execSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");

console.log("[manifest] collecting calculator list…");
const json = execSync(
  `"${join(root, "node_modules", ".bin", "esbuild")}" "${join(root, "scripts", "collect-manifest.ts")}" --bundle --platform=node --format=cjs --alias:@=${join(root, "src")} --outfile=/tmp/collect-manifest.cjs --log-level=error && node /tmp/collect-manifest.cjs`,
  { encoding: "utf-8", maxBuffer: 64 * 1024 * 1024 }
);
const entries = JSON.parse(json);

const ts = `// AUTO-GENERATED by scripts/generate-manifest.mjs — do not edit by hand.
// Regenerated on every build from src/data/*. Lightweight identity list used
// for listings, search, counts, and the sitemap. Full configs load on demand.
import type { CalculatorInfo } from "@/data/calculators";

export const calculatorManifest: (CalculatorInfo & { subcategory?: string })[] = ${JSON.stringify(entries, null, 2)};
`;

writeFileSync(join(root, "src", "data", "calculator-manifest.ts"), ts);
console.log(`[manifest] wrote ${entries.length} entries to src/data/calculator-manifest.ts`);
